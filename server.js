// ============================================================
// שרת Express – נקודת הכניסה של האפליקציה
// ============================================================

// טוען את משתני הסביבה מקובץ .env אל process.env
require('dotenv').config();

const express = require('express');
const app = express();

// ==========================================================
// Middleware מובנה – מפענח JSON מהגוף של הבקשה
// ==========================================================
app.use(express.json());

// ==========================================================
// Middleware מותאם – אימות auth-key על כל בקשה
// רץ לפני כל ראוטר. מדפיס לוג ובודק את הכותרת.
// ==========================================================
const validateAuth = require('./middleware/validateAuth');
app.use(validateAuth);

// ==========================================================
// חיבור הראוטרים – רק בקשות שעברו אימות מגיעות לפה
// ==========================================================
app.use('/courses', require('./routes/courses'));
app.use('/students', require('./routes/students'));

// ==========================================================
// תשובת JSON אחידה לנתיבים לא קיימים ולשגיאות בבקשה
// ==========================================================
app.use((req, res) => {
  res.status(404).json({ error: 'הנתיב לא נמצא.' });
});

app.use((err, req, res, next) => {
  if (res.headersSent) return next(err);

  if (err.type === 'entity.parse.failed') {
    return res.status(400).json({ error: 'גוף הבקשה אינו JSON תקין.' });
  }
  if (err.type === 'entity.too.large') {
    return res.status(413).json({ error: 'גוף הבקשה גדול מדי.' });
  }

  console.error(err);
  return res.status(500).json({ error: 'אירעה שגיאה פנימית בשרת.' });
});

// ==========================================================
// הפעלת השרת
// הפורט נקרא ממשתני הסביבה, ואם לא הוגדר – ברירת מחדל 3000
// ==========================================================
const PORT = process.env.PORT || 3000;
app.listen(PORT, () => {
  console.log(`השרת רץ על http://localhost:${PORT}`);
});