// ============================================================
// Middleware: אימות מפתח API
// פונקציה שרצה על כל בקשה, בודקת את הכותרת auth-key,
// ומחליטה אם להמשיך או לעצור עם 401
// ============================================================

// המפתח הסודי – נטען ממשתני הסביבה (קובץ .env), לא מופיע בקוד עצמו
const AUTH_KEY = process.env.AUTH_KEY;

// אם המפתח לא הוגדר – השרת יעצור מיד עם שגיאה ברורה,
// במקום לאפשר גישה עם מפתח undefined
if (!AUTH_KEY) {
  throw new Error('חסר משתנה סביבה AUTH_KEY. יש להגדיר אותו בקובץ .env');
}

function validateAuth(req, res, next) {
  // ==========================================================
  // שלב 1: תיעוד – מדפיסים כל בקשה שעוברת דרכנו
  // ==========================================================
  console.log(`[${new Date().toISOString()}] ${req.method} ${req.url}`);

  // ==========================================================
  // שלב 2: שולפים את הכותרת auth-key מהבקשה
  // req.headers הוא אובייקט עם כל הכותרות
  // ==========================================================
  const authKey = req.headers['auth-key'];

  // ==========================================================
  // שלב 3: בדיקה – האם הכותרת חסרה?
  // ==========================================================
  if (!authKey) {
    // מדפיסים ללוג – מי ניסה לגשת בלי מפתח
    console.log(`גישה נדחתה – חסר auth-key`);
    // מחזירים 401 – הלקוח לא מזוהה
    return res.status(401).json({ error: 'חסרה כותרת auth-key. גישה נדחתה.' });
  }

  // ==========================================================
  // שלב 4: בדיקה – האם הערך תואם?
  // ==========================================================
  if (authKey !== AUTH_KEY) {
    // המפתח קיים אבל שגוי
    console.log(`גישה נדחתה – auth-key שגוי`);
    return res.status(401).json({ error: 'auth-key שגוי. גישה נדחתה.' });
  }

  // ==========================================================
  // שלב 5: הכל תקין – מעבירים הלאה
  // next() אומר ל-Express: "סיימתי, תמשיך לראוטר"
  // ==========================================================
  console.log(`אושר – ממשיך לטיפול`);
  next();
}

module.exports = validateAuth;